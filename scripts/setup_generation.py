"""Download a pinned, Safetensors-only pretrained image-generation detector."""
import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.environ.setdefault('HF_HOME', str(ROOT / '.tools' / 'huggingface'))
os.environ.setdefault('HF_HUB_DISABLE_XET', '1')


def main():
    from huggingface_hub import HfApi, snapshot_download

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default=str(ROOT / 'models' / 'ai-image'))
    args = parser.parse_args()
    repository = 'Ateeqq/ai-vs-human-image-detector'
    revision = HfApi().model_info(repository).sha
    directory = Path(args.output)
    snapshot_download(repository, revision=revision, local_dir=directory, max_workers=2,
                      allow_patterns=['config.json', 'preprocessor_config.json', 'model.safetensors',
                                      'README.md', 'LICENSE', 'LICENSE.*'])
    card = {
        'name': 'SigLIP AI-image detector', 'version': revision[:12], 'purpose': 'ai_generation',
        'source_url': 'https://huggingface.co/' + repository, 'source_repository': repository,
        'source_revision': revision, 'license': 'Apache-2.0', 'ai_label': 'ai',
        'architecture': 'Pretrained SigLIP vision transformer, binary AI/human image head',
        'status': 'experimental', 'locally_validated': False, 'evaluation': None,
        'scope': 'AI-generated visual-pattern score for an image or sampled video frames. Not a factual-truth or authorship verdict.',
        'limitations': [
            'The pretrained AI-image detector has not been independently calibrated or accuracy-tested for this project. Its percentage is an experimental model score, not a verified probability of authorship.',
            'The model publisher reports overfitting concerns. New generators, screenshots, compression, drawings and unfamiliar image types can produce incorrect scores.',
            'Video AI scores describe selected frames only. They do not establish whether an entire video, its audio, or its motion was generated by AI.',
        ],
    }
    (directory / 'model-card.json').write_text(json.dumps(card, indent=2), encoding='utf8')
    print(json.dumps({'installed': str(directory), 'repository': repository, 'revision': revision,
                      'local_accuracy': 'not evaluated', 'license': card['license']}))


if __name__ == '__main__':
    main()
